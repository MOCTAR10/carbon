// Builds scripts/migrate-emission-factors-updates-2026.sql:
//   * grid electricity per country from Ember (lifecycle gCO2e/kWh, CC BY 4.0, via Our World in Data),
//     latest year available per country — replaces the "IEA/UNFCCC 2021" country factors, which are retired;
//   * corrections: refrigerants carried IPCC AR4 GWPs under an "AR5" label; air freight unit is per tonne.km.
//   1. Download https://ourworldindata.org/grapher/carbon-intensity-electricity.csv?v=1&csvType=full&useColumnShortNames=true
//   2. node scripts/factors/build-updates-2026.cjs <path to the csv>
const fs = require('fs')
const path = require('path')
if (!process.argv[2]) { console.error('Usage: node scripts/factors/build-updates-2026.cjs <carbon-intensity-electricity.csv>'); process.exit(1) }
const OUT = path.join(__dirname, '..', 'migrate-emission-factors-updates-2026.sql')

// Country names as stored on sites (src/app/dashboard/sites/page.tsx) → Ember entity
const COUNTRIES = {
  'Gabon': 'Gabon', 'Cameroun': 'Cameroon', 'Congo (Brazzaville)': 'Congo', 'Congo (Kinshasa)': 'Democratic Republic of Congo',
  'Guinée équatoriale': 'Equatorial Guinea', 'Tchad': 'Chad',
  'São Tomé-et-Príncipe': 'Sao Tome and Principe', 'Angola': 'Angola', 'Nigeria': 'Nigeria', "Côte d'Ivoire": "Cote d'Ivoire",
  'Sénégal': 'Senegal', 'Ghana': 'Ghana', 'Bénin': 'Benin', 'Togo': 'Togo', 'Burkina Faso': 'Burkina Faso', 'Mali': 'Mali',
  'Niger': 'Niger', 'Guinée': 'Guinea', 'Mauritanie': 'Mauritania', 'Maroc': 'Morocco', 'Tunisie': 'Tunisia', 'Algérie': 'Algeria',
  'Égypte': 'Egypt', 'Afrique du Sud': 'South Africa', 'Kenya': 'Kenya', 'Éthiopie': 'Ethiopia', 'Rwanda': 'Rwanda',
  'Ouganda': 'Uganda', 'Tanzanie': 'Tanzania', 'Madagascar': 'Madagascar', 'France': 'France', 'Belgique': 'Belgium',
  'Allemagne': 'Germany', 'Espagne': 'Spain', 'Italie': 'Italy', 'Pays-Bas': 'Netherlands', 'Portugal': 'Portugal',
  'Suisse': 'Switzerland', 'Royaume-Uni': 'United Kingdom', 'États-Unis': 'United States', 'Canada': 'Canada', 'Chine': 'China',
  'Inde': 'India', 'Brésil': 'Brazil', 'Japon': 'Japan', 'Turquie': 'Turkey', 'Émirats Arabes Unis': 'United Arab Emirates',
  'Arabie Saoudite': 'Saudi Arabia', 'Liban': 'Lebanon',
  'Afrique (moyenne)': 'Africa', 'Union européenne': 'European Union (27)', 'Monde': 'World',
}
// Centrafrique: Ember reports 0 gCO2e/kWh (data gap) — left out, sites there fall back to the Africa average
const slug = s => s.normalize('NFD').replace(/[̀-ͯ]/g, '').toLowerCase().replace(/[^a-z0-9]+/g, '_').replace(/^_|_$/g, '')

const latest = new Map()
for (const line of fs.readFileSync(process.argv[2], 'utf8').split(/\r?\n/).slice(1)) {
  const m = line.match(/^("?)(.*?)\1,([^,]*),(\d{4}),([\d.]+)$/)
  if (!m) continue
  const [, , entity, , year, value] = m
  const prev = latest.get(entity)
  if (!prev || Number(year) > prev.year) latest.set(entity, { year: Number(year), value: Number(value) })
}

const q = s => `'${String(s).replace(/'/g, "''")}'`
const rows = []
for (const [fr, ember] of Object.entries(COUNTRIES)) {
  const d = latest.get(ember)
  if (!d) throw new Error(`Ember: ${ember} absent`)
  const kg = Math.round(d.value) / 1000
  const id = `elec_ember_${slug(fr)}`
  const keywords = ['électricité', 'réseau', 'kWh', 'facture', 'courant', ...(fr === 'Gabon' ? ['SEEG'] : [])]
  rows.push(`  (${[q(id), "'energy'", "'electricity'", q(`Grid electricity — ${ember} (${d.year})`), q(`Électricité réseau — ${fr} (${d.year})`),
    "'kgCO2eq/kWh'", 0, kg, kg, 2, "'2-1 Électricité'", "'2-1'", q('Ember (Our World in Data)'),
    q(`Ember ${d.year} : intensité carbone de la production électrique, cycle de vie (amont inclus), ${d.value} gCO2e/kWh`),
    d.year, q(fr), 0.1, "'CC BY 4.0'", `ARRAY[${keywords.map(q).join(', ')}]::text[]`].join(', ')})`)
  console.log(id.padEnd(40), fr.padEnd(24), d.year, kg)
}

// IEA/UNFCCC 2021 country factors replaced by Ember (France keeps its ADEME factors by end use)
const RETIRED = ['elec_algeria', 'elec_br', 'elec_cameroon', 'elec_civ', 'elec_cn', 'elec_congo', 'elec_congo_rdc', 'elec_de',
  'elec_ethiopia', 'elec_eu', 'elec_gabon', 'elec_guinea', 'elec_in', 'elec_kenya', 'elec_morocco', 'elec_nigeria',
  'elec_senegal', 'elec_south_africa', 'elec_tunisia', 'elec_uk', 'elec_us', 'elec_world_avg']
// AR4 values labelled AR5 → AR5 (IPCC 2014, same basis as DEFRA 2024 and the rest of the library)
const GWP_FIX = [['r134a', 1430, 1300], ['r410a', 2088, 1924], ['r404a', 3922, 3943], ['r407c', 1774, 1624], ['r32', 675, 677]]
const BATCH = 'Migration 2026-10 : électricité Ember, PRG AR5, unité fret aérien'

const sql = `-- Emission factor library — 2026 updates (generated by scripts/factors/build-updates-2026.cjs, do not edit by hand)
--  1. Grid electricity for ${rows.length} countries/regions from Ember (lifecycle intensity of generation, upstream included,
--     CC BY 4.0, via Our World in Data), latest year per country. region = the country name used on sites.
--  2. The ${RETIRED.length} "IEA/UNFCCC 2021" country factors are retired: no longer offered, still valid in bilans that use them.
--  3. Refrigerants r134a, r410a, r404a, r407c, r32 carried IPCC AR4 GWPs under an "AR5" label: set to AR5.
--  4. air_freight is a per tonne.km factor (its name says "par tonne expédiée"): unit fixed.
-- Steps 2-4 run once (guarded by their entry in emission_factor_changes) so an admin's later edit is never reverted.
-- Saved entries keep the factor value they were saved with; certified bilans are never changed.

INSERT INTO emission_factors (id, category, subcategory, name, name_fr, unit, factor_upstream, factor_combustion, factor_total,
  scope, ghg_category, iso_category, source, source_ref, source_year, region, uncertainty, licence, keywords)
VALUES
${rows.join(',\n')}
ON CONFLICT (id) DO NOTHING;

DO $$
DECLARE
  f RECORD;
  fix RECORD;
BEGIN
  IF EXISTS (SELECT 1 FROM emission_factor_changes WHERE batch_label = ${q(BATCH)}) THEN
    RETURN;
  END IF;

  FOR f IN SELECT * FROM emission_factors WHERE id IN (${RETIRED.map(q).join(', ')}) AND status = 'active' LOOP
    UPDATE emission_factors SET status = 'retired', updated_at = NOW() WHERE id = f.id;
    INSERT INTO emission_factor_changes (factor_id, action, before, after, batch_label)
    VALUES (f.id, 'retired', jsonb_build_object('status', 'active'), jsonb_build_object('status', 'retired'), ${q(BATCH)});
  END LOOP;

  FOR fix IN SELECT * FROM (VALUES ${GWP_FIX.map(([id, from, to]) => `(${q(id)}, ${from}::numeric, ${to}::numeric)`).join(', ')}) AS v(id, old_value, new_value) LOOP
    UPDATE emission_factors
    SET factor_total = fix.new_value, factor_combustion = fix.new_value, source = 'IPCC AR5 (2014)', updated_at = NOW()
    WHERE id = fix.id AND factor_total = fix.old_value;
    IF FOUND THEN
      INSERT INTO emission_factor_changes (factor_id, action, before, after, batch_label)
      VALUES (fix.id, 'updated', jsonb_build_object('factor_total', fix.old_value), jsonb_build_object('factor_total', fix.new_value), ${q(BATCH)});
    END IF;
  END LOOP;

  UPDATE emission_factors SET unit = 'kgCO2eq/tonne.km', name_fr = 'Fret aérien (par tonne.km)', updated_at = NOW()
  WHERE id = 'air_freight' AND unit = 'kgCO2eq/km';
  IF FOUND THEN
    INSERT INTO emission_factor_changes (factor_id, action, before, after, batch_label)
    VALUES ('air_freight', 'updated', jsonb_build_object('unit', 'kgCO2eq/km'), jsonb_build_object('unit', 'kgCO2eq/tonne.km'), ${q(BATCH)});
  END IF;

  -- Marker: the batch is recorded even when nothing above applied (e.g. factors already edited by an admin)
  IF NOT EXISTS (SELECT 1 FROM emission_factor_changes WHERE batch_label = ${q(BATCH)}) THEN
    INSERT INTO emission_factor_changes (factor_id, action, before, after, batch_label)
    VALUES ('elec_ember_gabon', 'created', NULL, jsonb_build_object('note', 'lot appliqué'), ${q(BATCH)});
  END IF;
END $$;
`
fs.writeFileSync(OUT, sql)
console.log(rows.length, 'pays →', OUT)
